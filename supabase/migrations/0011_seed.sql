-- ── ผูกบัญชี Supabase Auth เข้ากับพนักงาน ──────────────────────────────────
-- สมัครผ่านหน้า /staff แล้วระบบสร้างแถว staff ให้อัตโนมัติในบทบาท STAFF
-- การเลื่อนเป็น SUPERVISOR / OWNER ต้องแก้ด้วย SQL โดยเจตนา ไม่เปิดให้ทำเองในแอป

create or replace function fn_handle_new_auth_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into staff (branch_id, auth_user_id, full_name, role)
  values (
    (select branch_id from branch where deleted_at is null order by created_at limit 1),
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    'STAFF'
  )
  on conflict (auth_user_id) do nothing;
  return new;
end $$;

create trigger t01_handle_new_auth_user
  after insert on auth.users
  for each row execute function fn_handle_new_auth_user();
